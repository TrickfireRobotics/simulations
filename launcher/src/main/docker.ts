import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { containerName, containerRepository, probe, type Stage } from "./system";

export const writeDockerEnvironment = async (repository: string): Promise<void> => {
    const dockerDirectory = path.join(repository, "docker");
    const defaults = await readFile(path.join(dockerDirectory, ".env.defaults"), "utf8");
    let overrides = "";
    try {
        overrides = await readFile(path.join(dockerDirectory, ".env.local"), "utf8");
    } catch {
        overrides = "";
    }

    const detected: string[] = ["# host-detected"];
    if (process.platform === "darwin" || process.platform === "win32") {
        detected.push("DISPLAY=host.docker.internal:0", "VGL_DISPLAY=:88", "VGL_COMPRESS=proxy");
    } else {
        detected.push(`DISPLAY=${process.env.DISPLAY || ":0"}`);
        const inputGroup = await probe("getent", ["group", "input"]);
        const inputGid = inputGroup.output.split(":")[2];
        if (inputGroup.ok && inputGid) detected.push(`INPUT_GID=${inputGid}`);
    }

    const nvidia = await probe("nvidia-smi", ["-L"]);
    const runtimes = await probe("docker", ["info", "--format", "{{json .Runtimes}}"]);
    const hasNvidia =
        process.platform === "linux" && nvidia.ok && runtimes.output.includes("nvidia");
    detected.push(`SIM_GPU_RUNTIME=${hasNvidia ? "nvidia" : ""}`);
    if (hasNvidia) {
        detected.push(
            "NVIDIA_VISIBLE_DEVICES=all",
            "NVIDIA_DRIVER_CAPABILITIES=graphics,display,compute,utility",
            "__EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/10_nvidia.json"
        );
    }

    const output = [
        "# generated by TrickFire Sim, do not edit",
        "# use docker/.env.local for personal overrides",
        "",
        defaults.trim(),
        overrides ? `\n# local overrides\n${overrides.trim()}` : "",
        "",
        detected.join("\n"),
        ""
    ].join("\n");
    await writeFile(path.join(dockerDirectory, ".env"), output, "utf8");
};

export const dockerInitializationStages = (repository: string): Stage[] => [
    {
        source: "docker",
        command: "docker",
        args: [
            "compose",
            "--project-directory",
            repository,
            "--env-file",
            path.join(repository, "docker", ".env"),
            "-f",
            path.join(repository, "docker", "docker-compose.yml"),
            "up",
            "-d",
            "--build"
        ],
        cwd: repository
    },
    {
        source: "setup",
        command: "docker",
        args: [
            "exec",
            containerName,
            "bash",
            "-lc",
            `cd ${containerRepository} && python3 -m pip install --break-system-packages -e . && bash .devcontainer/x_server.sh`
        ],
        cwd: repository
    }
];
