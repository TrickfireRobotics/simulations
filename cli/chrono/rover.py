@dataclass
class ClassifiedTree:
    """The rover's topology after fixed-joint collapsing."""

    chassis_links: list[str]
    pivots: list[dict]  # in root-first order, each with its contributing links
    stations: list[dict]


def _classify(model: urdf.Model, hints: Hints) -> ClassifiedTree:
    """Work out which URDF links become which Chrono bodies.

    Fixed joints are collapsed into their parent, which is what turns the exported
    base_link plus extrusion frame into one chassis body. Joints named in the hints are
    treated as pivots regardless of the type the URDF gives them, which is how the
    rocker and bogie pivots are restored.
    """
    pivot_joints = set(hints.pivots)
    station_joints = set(hints.wheel_stations)

    for name in pivot_joints | station_joints:
        if name not in model.joints:
            available = ", ".join(sorted(model.joints))
            raise RoverImportError(
                f"the hints file names joint '{name}', which the URDF does not have. "
                f"Joints in the URDF: {available}"
            )

    # Bodies are the root plus every joint-separated child. Everything else collapses
    # into the nearest body above it.
    body_of: dict[str, str] = {}

    def assign(link: str, body: str) -> None:
        body_of[link] = body
        for joint in model.children_of(link):
            if joint.name in pivot_joints or joint.name in station_joints:
                assign(joint.child, joint.child)
            else:
                if joint.kind not in {"fixed"}:
                    warn(
                        f"joint '{joint.name}' is {joint.kind} in the URDF but is not listed "
                        "in the hints, so it is being collapsed as if it were fixed. Add it "
                        "to pivots or wheel_stations if it should move."
                    )
                assign(joint.child, body)

    assign(model.root, model.root)

    chassis_links = [link for link, body in body_of.items() if body == model.root]

    # Pivots in root-first order, which the simulator requires so each pivot's parent is
    # already declared when it is built.
    ordered: list[str] = []

    def walk(body: str) -> None:
        for joint in sorted(model.children_of(body), key=lambda j: j.name):
            if joint.name in pivot_joints:
                ordered.append(joint.name)
                walk(joint.child)
            elif joint.name not in station_joints:
                nested_pivots = [
                    nested
                    for nested in model.children_of(joint.child)
                    if nested.name in pivot_joints
                ]
                for nested in nested_pivots:
                    ordered.append(nested.name)
                    walk(nested.child)

    walk(model.root)
    ordered.extend(sorted(pivot_joints - set(ordered)))

    pivots = []
    for name in ordered:
        joint = model.joints[name]
        pivots.append(
            {
                "joint": name,
                "body": joint.child,
                "parent_body": body_of[joint.parent],
                "links": [link for link, body in body_of.items() if body == joint.child],
            }
        )

    stations = []
    for name in sorted(station_joints):
        joint = model.joints[name]
        stations.append(
            {
                "joint": name,
                "body": joint.child,
                "parent_body": body_of[joint.parent],
            }
        )

    return ClassifiedTree(chassis_links, pivots, stations)


