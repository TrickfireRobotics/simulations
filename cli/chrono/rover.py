def _convert_meshes(model: urdf.Model, rover_name: str) -> dict[Path, str]:
    """Convert every referenced STL to OBJ, which is the only mesh format Chrono reads.

    Returns a map from the source path to the path to put in the config, relative to
    chrono/ so the config stays portable.
    """
    import trimesh

    destination = GENERATED_DIR / rover_name / "meshes"
    destination.mkdir(parents=True, exist_ok=True)

    converted: dict[Path, str] = {}
    for link in model.links.values():
        for geometry in link.visual + link.collision:
            if geometry.kind != "mesh" or geometry.mesh is None:
                continue
            if geometry.mesh in converted:
                continue

            target = destination / (geometry.mesh.stem + ".obj")
            if not target.is_file() or target.stat().st_mtime < geometry.mesh.stat().st_mtime:
                mesh = trimesh.load(geometry.mesh, force="mesh")
                target.write_text(trimesh.exchange.obj.export_obj(mesh, include_normals=False))
            converted[geometry.mesh] = str(target.relative_to(CHRONO_DIR))

    if converted:
        info(f"converted {len(converted)} mesh(es) to {_relative(destination)}")
    return converted


def _visual_entries(
    model: urdf.Model, links: list[str], frame: str, meshes: dict[Path, str]
) -> list[dict]:
    entries = []
    for link in sorted(links):
        for geometry in model.links[link].visual:
            if geometry.kind != "mesh" or geometry.mesh is None:
                continue
            rotation, translation = _transform_to(model, link, frame)
            position = translation + rotation @ np.array(geometry.position)
            combined = rotation @ _rotation(geometry.rpy)

            entries.append(
                {
                    "file": meshes[geometry.mesh],
                    "position": [round(float(v), 6) for v in position],
                    "rotation": [round(math.degrees(a), 4) for a in _to_rpy(combined)],
                    "scale": geometry.scale,
                    "color": [round(float(c), 3) for c in geometry.color],
                }
            )
    return entries


def _to_rpy(rotation: np.ndarray) -> tuple[float, float, float]:
    """Extrinsic X-Y-Z Euler angles from a rotation matrix."""
    pitch = -math.asin(max(-1.0, min(1.0, rotation[2][0])))
    if abs(math.cos(pitch)) < 1e-9:
        # Gimbal lock: fold the degenerate rotation into yaw, which is an equivalent
        # orientation rather than an approximation.
        return math.atan2(-rotation[1][2], rotation[1][1]), pitch, 0.0
    roll = math.atan2(rotation[2][1], rotation[2][2])
    yaw = math.atan2(rotation[1][0], rotation[0][0])
    return roll, pitch, yaw


def _collision_entries(
    model: urdf.Model, links: list[str], frame: str, mode: str, padding: float
) -> list[dict]:
    """Approximate a body's collision volume with primitives.

    The development plan rejects triangle-mesh chassis collision: it is slow and it
    behaves badly against SCM. One oriented bounding box per visual mesh is a deliberate,
    inspectable approximation, and the resulting boxes are meant to be reviewed and
    pruned in the hints file rather than trusted blindly.
    """
    import trimesh

    if mode == "none":
        return []

    entries = []
    for link in sorted(links):
        for geometry in model.links[link].visual:
            if geometry.kind != "mesh" or geometry.mesh is None:
                continue

            mesh = trimesh.load(geometry.mesh, force="mesh")
            if geometry.scale != 1.0:
                mesh.apply_scale(geometry.scale)

            rotation, translation = _transform_to(model, link, frame)
            local = rotation @ _rotation(geometry.rpy)
            offset = translation + rotation @ np.array(geometry.position)

            if mode == "aabb_per_mesh":
                extents = mesh.bounds[1] - mesh.bounds[0]
                centre = (mesh.bounds[0] + mesh.bounds[1]) / 2.0
                box_rotation = local
            else:
                # Oriented box: tighter than an axis-aligned one on the diagonal members
                # of an extrusion frame, which is most of this chassis.
                transform, extents = trimesh.bounds.oriented_bounds(mesh)
                inverse = np.linalg.inv(transform)
                centre = inverse[:3, 3]
                box_rotation = local @ inverse[:3, :3]

            entries.append(
                {
                    "type": "box",
                    "position": [round(float(v), 6) for v in offset + local @ centre],
                    "rotation": [round(math.degrees(a), 4) for a in _to_rpy(box_rotation)],
                    "dimensions": [round(float(max(e + padding, 1e-3)), 6) for e in extents],
                }
            )
    return entries


