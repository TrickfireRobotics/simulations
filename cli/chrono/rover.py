"""Turning the chassis URDF into a rover config.

The URDF is the geometry and mass-property source, but it is not a usable rover model
on its own: the suspension pivots are exported as fixed joints, several links carry
1e-09 kg placeholder masses, and the chassis collision geometry is full triangle meshes.

So the import is URDF plus a hints file. The hints say which fixed joints are really
pivots, what their travel limits are, whether there is a differential, and how the
chassis collision volume should be approximated. Both are versioned, and the generated
config records the URDF's hash, so a chassis revision that changes the geometry shows up
as a changed hash rather than as a quietly different result.
"""

from __future__ import annotations

import datetime as dt
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import yaml

from ..output import info, warn
from ..paths import CHRONO_DIR, GAZEBO_DIR, REPO_DIR
from . import configs, urdf
from .schema import SchemaError, validate

ROVER_SCHEMA_VERSION = 1

# Where generated artefacts go. Separate from configs/ because they are outputs.
GENERATED_DIR = CHRONO_DIR / "data" / "rovers"


class RoverImportError(Exception):
    pass


def _relative(path: Path) -> str:
    """Path relative to the repo root when it is inside it, absolute otherwise."""
    try:
        return str(path.resolve().relative_to(REPO_DIR))
    except ValueError:
        return str(path)


@dataclass
class Hints:
    """The judgement calls the URDF cannot express. Authored once per rover."""

    name: str
    urdf: str
    pivots: dict  # joint name -> {role, axis, limits_deg, spring_*}
    wheel_stations: dict  # joint name -> {id, mirror, mount_roll_deg}
    differential: dict
    chassis_collision: dict
    xacro_args: dict
    mass_overrides: dict
    battery: str
    body_friction: float
    body_restitution: float

    @classmethod
    def load(cls, path: Path) -> Hints:
        data = yaml.safe_load(path.read_text()) or {}
        missing = [k for k in ("name", "urdf", "pivots", "wheel_stations") if k not in data]
        if missing:
            raise RoverImportError(f"{path} is missing required keys: {', '.join(missing)}")
        return cls(
            name=data["name"],
            urdf=data["urdf"],
            pivots=data["pivots"],
            wheel_stations=data["wheel_stations"],
            differential=data.get("differential", {"type": "none"}),
            chassis_collision=data.get("chassis_collision", {"mode": "obb_per_mesh"}),
            xacro_args=data.get("xacro_args", {}),
            mass_overrides=data.get("mass_overrides", {}),
            battery=data.get("battery", ""),
            body_friction=data.get("body_friction", 0.8),
            body_restitution=data.get("body_restitution", 0.0),
        )


def import_rover(hints_path: Path, output: Path | None = None) -> Path:
    """Generate a rover config from a URDF and its hints file."""
    hints_path = hints_path.resolve()
    hints = Hints.load(hints_path)

    urdf_path = Path(hints.urdf)
    if not urdf_path.is_absolute():
        urdf_path = (REPO_DIR / urdf_path).resolve()
    if not urdf_path.is_file():
        raise RoverImportError(f"URDF not found: {urdf_path}")

    search_paths = [GAZEBO_DIR, urdf_path.parent.parent.parent]

    info(f"rendering {_relative(urdf_path)}")
    rendered = urdf.render_xacro(urdf_path, hints.xacro_args, search_paths)
    generated = urdf.write_urdf(rendered, GENERATED_DIR / hints.name / "rover.urdf")
    info(f"wrote {_relative(generated)}")

    model = urdf.parse(urdf_path, hints.xacro_args, search_paths)
    tree = _classify(model, hints)
    meshes = _convert_meshes(model, hints.name)

    rover = _build_config(model, tree, hints, meshes, generated)

    try:
        validate(rover, "rover", source="generated rover config")
    except SchemaError as exc:
        raise RoverImportError(f"the generated config does not validate:\n{exc}") from exc

    destination = output or (configs.kind_dir("rover") / f"{hints.name}.yaml")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        "# GENERATED by `sim chrono rover import`.\n"
        f"# Source: {_relative(urdf_path)}\n"
        f"# Hints:  {_relative(hints_path)}\n"
        "#\n"
        "# Re-import after a chassis revision rather than editing this file: the mass\n"
        "# properties and geometry come from the URDF, and the judgement calls that are\n"
        "# not in the URDF belong in the hints file.\n\n"
        + yaml.safe_dump(rover, sort_keys=False, default_flow_style=None)
    )
    info(f"wrote {_relative(destination)}")

    _report_mass(rover)
    return destination


