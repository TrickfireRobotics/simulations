def _rotation(rpy: list[float]) -> np.ndarray:
    """Extrinsic X-Y-Z rotation matrix, matching URDF's rpy convention."""
    roll, pitch, yaw = rpy
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)
    return np.array(
        [
            [cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
            [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
            [-sp, cp * sr, cp * cr],
        ]
    )


def _transform_to(model: urdf.Model, link: str, target: str) -> tuple[np.ndarray, np.ndarray]:
    """Transform from `link`'s frame into `target`'s, walking up the joint tree."""
    rotation = np.eye(3)
    translation = np.zeros(3)
    current = link

    while current != target:
        joint = model.joint_to(current)
        if joint is None:
            raise RoverImportError(f"link '{link}' is not below '{target}' in the tree")
        joint_rotation = _rotation(joint.rpy)
        translation = np.array(joint.position) + joint_rotation @ translation
        rotation = joint_rotation @ rotation
        current = joint.parent

    return rotation, translation


def _combine_mass(model: urdf.Model, links: list[str], frame: str) -> dict:
    """Sum the mass properties of several links, expressed in one body's frame.

    The parallel-axis theorem is applied in full, including the off-diagonal terms, so a
    collapsed body's tensor is correct rather than only approximately so.
    """
    total_mass = 0.0
    weighted_com = np.zeros(3)
    contributions = []

    for link in links:
        inertial = model.links[link].inertial
        if inertial.mass <= 0:
            continue
        rotation, translation = _transform_to(model, link, frame)
        com = translation + rotation @ np.array(inertial.com)

        ixx, iyy, izz, ixy, ixz, iyz = inertial.inertia
        tensor = np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])
        tensor = rotation @ tensor @ rotation.T

        total_mass += inertial.mass
        weighted_com += inertial.mass * com
        contributions.append((inertial.mass, com, tensor))

    if total_mass <= 0:
        return {
            "mass": 0.0,
            "com": [0.0] * 3,
            "inertia_xx": [0.0] * 3,
            "inertia_xy": [0.0] * 3,
            "provenance": "placeholder",
        }

    centre = weighted_com / total_mass
    combined = np.zeros((3, 3))
    for mass, com, tensor in contributions:
        offset = com - centre
        combined += tensor + mass * (np.dot(offset, offset) * np.eye(3) - np.outer(offset, offset))

    return {
        "mass": round(float(total_mass), 6),
        "com": [round(float(v), 6) for v in centre],
        "inertia_xx": [
            round(float(combined[0][0]), 9),
            round(float(combined[1][1]), 9),
            round(float(combined[2][2]), 9),
        ],
        "inertia_xy": [
            round(float(combined[0][1]), 9),
            round(float(combined[0][2]), 9),
            round(float(combined[1][2]), 9),
        ],
        "provenance": "cad",
    }


