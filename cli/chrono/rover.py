def _build_config(
    model: urdf.Model,
    tree: ClassifiedTree,
    hints: Hints,
    meshes: dict[Path, str],
    generated_urdf: Path,
) -> dict:
    chassis_frame = model.root
    collision_mode = hints.chassis_collision.get("mode", "obb_per_mesh")
    padding = float(hints.chassis_collision.get("padding", 0.0))

    chassis_mass = _apply_override(
        _combine_mass(model, tree.chassis_links, chassis_frame),
        hints.mass_overrides.get("chassis"),
    )

    chassis_collision = hints.chassis_collision.get("shapes")
    if chassis_collision is None:
        chassis_collision = _collision_entries(
            model, tree.chassis_links, chassis_frame, collision_mode, padding
        )
    if not chassis_collision:
        raise RoverImportError(
            "the chassis has no collision geometry. Set chassis_collision.shapes in the "
            "hints file, or use a mode other than 'none'."
        )

    pivots = []
    for entry in tree.pivots:
        joint = model.joints[entry["joint"]]
        hint = hints.pivots[entry["joint"]]

        rotation, translation = _transform_to(model, joint.child, chassis_frame)
        # The joint's own origin is already included by walking up to the child, so the
        # pivot centre is the child's frame origin expressed in the chassis frame.
        axis_world = rotation @ np.array(joint.axis)

        pivot = {
            "name": hint.get("name", entry["joint"]),
            "parent": "chassis"
            if entry["parent_body"] == chassis_frame
            else _pivot_name(hints, entry["parent_body"], model),
            "position": [round(float(v), 6) for v in translation],
            "axis": hint.get("axis") or _snap_axis(axis_world, entry["joint"]),
            "mass_properties": _apply_override(
                _combine_mass(model, entry["links"], joint.child),
                hints.mass_overrides.get(entry["joint"]),
            ),
            "visual": _visual_entries(model, entry["links"], joint.child, meshes),
        }

        limits = hint.get("limits_deg")
        if limits is None and joint.limits:
            limits = [
                round(math.degrees(joint.limits[0]), 3),
                round(math.degrees(joint.limits[1]), 3),
            ]
        if limits:
            pivot["limits_deg"] = limits

        for key in ("spring_stiffness", "spring_damping", "rest_angle_deg"):
            if key in hint:
                pivot[key] = hint[key]

        if hint.get("collision"):
            pivot["collision"] = hint["collision"]

        pivots.append(pivot)

    stations = []
    for entry in tree.stations:
        joint = model.joints[entry["joint"]]
        hint = hints.wheel_stations[entry["joint"]]

        rotation, translation = _transform_to(model, joint.child, chassis_frame)
        axis_world = rotation @ np.array(joint.axis)

        station = {
            "id": hint["id"],
            "parent": "chassis"
            if entry["parent_body"] == chassis_frame
            else _pivot_name(hints, entry["parent_body"], model),
            "position": [round(float(v), 6) for v in translation],
            "axis": hint.get("axis") or _snap_axis(axis_world, entry["joint"]),
        }
        for key in ("wheel_package", "actuator", "mount_roll_deg", "mirror"):
            if key in hint:
                station[key] = hint[key]
        stations.append(station)

    config = {
        "schema_version": ROVER_SCHEMA_VERSION,
        "name": hints.name,
        "description": f"{hints.name}, imported from {Path(hints.urdf).name}",
        "source": {
            "urdf": str(Path(hints.urdf)),
            "urdf_hash": configs.file_hash(generated_urdf),
            "rendered_urdf": str(generated_urdf.relative_to(CHRONO_DIR)),
            "generated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "xacro_args": hints.xacro_args,
        },
        "body_friction": hints.body_friction,
        "body_restitution": hints.body_restitution,
        "chassis": {
            "mass_properties": chassis_mass,
            "visual": _visual_entries(model, tree.chassis_links, chassis_frame, meshes),
            "collision": chassis_collision,
        },
        "pivots": pivots,
        "differential": hints.differential,
        "wheels": stations,
    }
    if hints.battery:
        config["battery"] = hints.battery
    return config


def _pivot_name(hints: Hints, body: str, model: urdf.Model) -> str:
    for joint_name, hint in hints.pivots.items():
        if model.joints[joint_name].child == body:
            return hint.get("name", joint_name)
    raise RoverImportError(f"no pivot produces body '{body}'")


def _snap_axis(axis: np.ndarray, joint: str) -> list[float]:
    """Snap a near-cardinal axis onto the exact positive cardinal direction.

    Two things happen here.

    First, rounding: URDF origins carry rpy values like 1.5708, so a transformed axis
    comes out as (1e-5, 0.9999999, 0). The simulator insists on exact cardinal axes, and
    dropping a 1e-5 component is right; a genuinely tilted axis is an error worth raising.

    Second, sign. This export mirrors the right-hand side, so its joints come out about
    -y while the left side's are about +y. A revolute joint about -y and the same joint
    about +y are the same joint - only the sign of the measured angle differs - but the
    drive torque is applied about the joint's own axis. Leaving the right side at -y
    would make a positive command spin those three wheels backwards, and the rover would
    turn on the spot instead of driving. So every axis is normalised to point positively
    and the handedness of the wheel itself is carried by `mirror` instead.
    """
    normalised = axis / np.linalg.norm(axis)
    dominant = int(np.argmax(np.abs(normalised)))
    residual = float(np.linalg.norm(np.delete(normalised, dominant)))

    if residual > 1e-3:
        raise RoverImportError(
            f"joint '{joint}' has axis {normalised.round(6).tolist()} in the chassis frame, "
            f"which is {residual:.4f} off a cardinal direction. Either fix the URDF origin "
            "or set the axis explicitly in the hints file."
        )

    snapped = [0.0, 0.0, 0.0]
    snapped[dominant] = 1.0
    if normalised[dominant] < 0:
        info(
            f"joint '{joint}' points along the negative axis in the chassis frame; "
            "normalising it to positive so one command drives every wheel the same way"
        )
    return snapped


def _apply_override(properties: dict, override: dict | None) -> dict:
    if not override:
        return properties
    merged = dict(properties)
    merged.update(override)
    merged.setdefault("provenance", "measured")
    return merged


def _report_mass(rover: dict) -> None:
    """Print the model's total mass and flag it, because this is the check that matters.

    The URDF only contains the structural parts CAD knew about. Battery, electronics,
    arm and payload are not in it, so the total will be well under the real rover and
    every load-dependent result will be optimistic until it is reconciled.
    """
    total = rover["chassis"]["mass_properties"]["mass"]
    for pivot in rover.get("pivots", []):
        total += pivot["mass_properties"]["mass"]

    info(f"model mass excluding wheels: {total:.2f} kg")
    warn(
        f"this is the CAD structural mass only ({total:.2f} kg plus wheels). Battery, "
        "electronics, arm and payload are not in the URDF. Add them as mass_overrides in "
        "the hints file once the complete rover has been weighed - until then every "
        "load, traction and energy result is optimistic."
    )
